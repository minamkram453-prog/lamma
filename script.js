const USERS_STORAGE_KEY = 'lamma_users';
const CURRENT_USER_KEY = 'lamma_current_user';

function getStoredUsers() {
  try {
    return JSON.parse(localStorage.getItem(USERS_STORAGE_KEY) || '[]');
  } catch (error) {
    return [];
  }
}

function setCurrentUser(name) {
  if (name) {
    localStorage.setItem(CURRENT_USER_KEY, name);
  }
}

function showLoginForm(showLogin) {
  const loginFormElement = document.getElementById('loginForm');
  const signupFormElement = document.getElementById('signupForm');

  if (loginFormElement) {
    loginFormElement.classList.toggle('hidden', !showLogin);
  }

  if (signupFormElement) {
    signupFormElement.classList.toggle('hidden', showLogin);
  }

  if (!showLogin && loginError) {
    loginError.textContent = '';
  }

  if (showLogin && signupMessage) {
    signupMessage.textContent = '';
  }
}

function toggleAuthState(isLoggedIn) {
  if (loginScreen) loginScreen.classList.toggle('hidden', isLoggedIn);
  if (appShell) appShell.classList.toggle('hidden', !isLoggedIn);
}

function logoutUser() {
  localStorage.removeItem('lamma_auth');
  localStorage.removeItem(CURRENT_USER_KEY);

  if (loginForm) loginForm.reset();
  if (document.getElementById('signupForm')) document.getElementById('signupForm').reset();
  if (loginError) loginError.textContent = '';
  if (signupMessage) signupMessage.textContent = '';

  showLoginForm(true);
  toggleAuthState(false);
}

function handleLogin(event) {
  event.preventDefault();

  const username = usernameInput?.value.trim() || '';
  const password = passwordInput?.value.trim() || '';

  if (!username) {
    loginError.textContent = 'يرجى إدخال اسم المستخدم';
    return;
  }

  if (!password) {
    loginError.textContent = 'يرجى إدخال كلمة المرور';
    return;
  }

  const storedUsers = getStoredUsers();
  const matchedUser = storedUsers.find((user) => {
    const samePhone = user.phone && user.phone.replace(/\s+/g, '') === username.replace(/\s+/g, '');
    const sameEmail = user.email && user.email.toLowerCase() === username.toLowerCase();
    const sameName = user.name && user.name.toLowerCase() === username.toLowerCase();
    return samePhone || sameEmail || sameName;
  });

  if (username === validCredentials.username && password === validCredentials.password) {
    localStorage.setItem('lamma_auth', 'true');
    setCurrentUser(validCredentials.username);
    loginError.textContent = '';
    toggleAuthState(true);
    return;
  }

  if (matchedUser) {
    if (matchedUser.password !== password) {
      loginError.textContent = 'كلمة المرور غير صحيحة';
      return;
    }

    localStorage.setItem('lamma_auth', 'true');
    setCurrentUser(matchedUser.name || matchedUser.phone || matchedUser.email);
    loginError.textContent = '';
    toggleAuthState(true);
    return;
  }

  if (username === validCredentials.username) {
    loginError.textContent = 'كلمة المرور غير صحيحة';
    return;
  }

  if (username && password) {
    loginError.textContent = 'هذا الحساب غير موجود، يرجي إنشاء حساب جديد';
    return;
  }

  loginError.textContent = 'اسم المستخدم غير صحيح';
}

function handleSignup(event) {
  event.preventDefault();

  const signupPhone = document.getElementById('signupPhone')?.value.trim() || '';
  const signupPassword = document.getElementById('signupPassword')?.value.trim() || '';

  if (!signupPhone || !signupPassword) {
    if (signupMessage) signupMessage.textContent = 'يرجى ملء جميع الحقول';
    return;
  }

  if (signupPassword.length < 6) {
    if (signupMessage) signupMessage.textContent = 'يجب أن تكون كلمة المرور 6 أحرف على الأقل';
    return;
  }

  const storedUsers = getStoredUsers();
  const alreadyExists = storedUsers.some(
    (user) => user.phone && user.phone.replace(/\s+/g, '') === signupPhone.replace(/\s+/g, '')
  );

  if (alreadyExists) {
    if (signupMessage) signupMessage.textContent = 'هذا الرقم مسجل بالفعل';
    return;
  }

  const newUser = {
    phone: signupPhone,
    password: signupPassword
  };

  storedUsers.push(newUser);
  localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(storedUsers));
  localStorage.setItem('lamma_auth', 'true');
  setCurrentUser(signupPhone);

  document.getElementById('signupForm')?.reset();
  if (signupMessage) signupMessage.textContent = 'تم إنشاء الحساب بنجاح';
  showLoginForm(true);
  toggleAuthState(true);
}

function parseCurrencyValue(value) {
  const numeric = Number(String(value).replace(/[^\d]/g, ''));
  return Number.isFinite(numeric) ? numeric : 0;
}

function renderParticipants(lang = 'ar') {
  if (!tableBody) return;

  tableBody.innerHTML = participants
    .map((member) => {
      const scheduleText = scheduleLabels[member.schedule]?.[lang] || member.schedule;
      const dueValue = parseCurrencyValue(member.dueAmount);
      const paidValue = parseCurrencyValue(member.paidAmount);
      const remainingValue = Math.max(dueValue - paidValue, 0);

      return `
        <tr>
          <td>
            <div class="member-cell">
              <strong>${member.name}</strong>
            </div>
          </td>
          <td>${scheduleText}</td>
          <td>${member.amount} / يومي</td>
          <td>${member.dueAmount}</td>
          <td>${member.paidAmount}</td>
          <td>${remainingValue} جنيه</td>
        </tr>
      `;
    })
    .join('');

  const paid = participants.filter((p) => p.status === 'paid').length;
  const pending = participants.filter((p) => p.status === 'pending').length;
  const due = participants.filter((p) => p.status === 'due').length;

  if (paidCount) paidCount.textContent = String(paid);
  if (pendingCount) pendingCount.textContent = String(pending);
  if (payoutCount) payoutCount.textContent = String(due);
}

function renderCycleOrders(lang = 'ar') {
  const container = document.getElementById('cycleOrderFlow');
  if (!container) return;

  const rows = [
    { key: 'monthly', label: lang === 'ar' ? 'شهري' : 'Monthly', names: cycleOrder.monthly },
    { key: 'semiMonthly', label: lang === 'ar' ? 'نصف شهري' : 'Semi-monthly', names: cycleOrder.semiMonthly },
    { key: 'weekly', label: lang === 'ar' ? 'أسبوعي' : 'Weekly', names: cycleOrder.weekly }
  ];

  container.innerHTML = rows
    .map(({ label, names }) => `
      <div class="order-table-card">
        <div class="schedule-order-header">${label}</div>
        <table>
          <thead>
            <tr>
              <th>الترتيب</th>
              <th>الاسم</th>
            </tr>
          </thead>
          <tbody>
            ${names
              .map(
                (name, index) => `
                  <tr>
                    <td>${index + 1}</td>
                    <td class="member-name-cell"><span>${name}</span></td>
                  </tr>
                `
              )
              .join('')}
          </tbody>
        </table>
      </div>
    `)
    .join('');
}

function applyLanguage(lang) {
  const dict = translations[lang];
  const translationNodes = document.querySelectorAll('[data-i18n]');
  const placeholderNodes = document.querySelectorAll('[data-i18n-placeholder]');

  translationNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key]) {
      node.textContent = dict[key];
    }
  });

  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dict[key]) {
      node.placeholder = dict[key];
    }
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', lang === 'ar');
  document.body.classList.toggle('ltr', lang === 'en');

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });

  renderParticipants(lang);
  renderCycleOrders(lang);
}

